export type InventoryCategory = string;
export type InventoryUnitType = string;
export type InventoryStatus = "active" | "inactive";
export type InventoryItem = {
  id: string;
  sku: string;
  name: string;
  category: InventoryCategory;
  brand: string;
  description: string;
  unitType: InventoryUnitType;
  packSize: string;
  openingStock: number;
  currentStock: number;
  minimumStock: number;
  maximumStock: number | null;
  reorderQuantity: number | null;
  supplier: string;
  purchasePrice: number;
  sellingPrice: number | null;
  taxPercent: number | null;
  lastPurchaseDate: string;
  warehouse: string;
  rackNumber: string;
  shelf: string;
  bin: string;
  hasExpiry: boolean;
  manufacturingDate: string;
  expiryDate: string;
  batchNumber: string;
  status: InventoryStatus;
  internalNotes: string;
  createdAt: string;
};
export type InventoryPayload = Omit<
  InventoryItem,
  "id" | "sku" | "currentStock" | "createdAt"
>;
type InventoryRow = {
  id: string;
  store_id: string | null;
  name: string;
  category: InventoryCategory;
  brand: string;
  description: string;
  unit_type: InventoryUnitType;
  pack_size: string;
  opening_stock: string;
  current_stock: string;
  minimum_stock: string;
  maximum_stock: string | null;
  reorder_quantity: string | null;
  supplier: string;
  purchase_price: string;
  selling_price: string | null;
  tax_percent: string | null;
  last_purchase_date: string | Date | null;
  warehouse: string;
  rack_number: string;
  shelf: string;
  bin: string;
  has_expiry: boolean;
  manufacturing_date: string | Date | null;
  expiry_date: string | Date | null;
  batch_number: string;
  status: InventoryStatus;
  internal_notes: string;
  created_at: Date;
};
